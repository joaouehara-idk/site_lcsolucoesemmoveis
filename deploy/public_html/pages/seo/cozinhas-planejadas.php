<section id="materiais">
    <h2>Melhores materiais para cozinha</h2>
    <p>A escolha dos materiais é crucial para a durabilidade e beleza da sua cozinha planejada:</p>
    <ul>
        <li><strong>MDF hidrofóbico:</strong> resistente à umidade, ideal para armários próximos a pias e fogão.</li>
        <li><strong>Compensado naval:</strong> ainda mais resistente à água, recomendado para áreas muito úmidas.</li>
        <li><strong>Ferragens Blum:</strong> corrediças com amortecedor que garantem suavidade e silêncio.</li>
        <li><strong>Nanitop ou Silestone:</strong> bancadas resistentes a manchas e calor.</li>
        <li><strong>Vidro temperado:</strong> para portas de armários e backsplash, fácil de limpar.</li>
    </ul>
</section>

<section id="ergonomia">
    <h2>Ergonomia na cozinha</h2>
    <p>Uma cozinha planejada deve priorizar a ergonomia para evitar desconforto e lesões. Os princípios básicos são:</p>
    <ul>
        <li><strong>Triângulo de trabalho:</strong> geladeira, pia e fogão formam um triângulo com distâncias entre 1,20m e 2,70m.</li>
        <li><strong>Altura das bancadas:</strong> entre 85cm e 95cm, dependendo da altura dos usuários.</li>
        <li><strong>Armários superiores:</strong> a 50-60cm da bancada, com prateleiras ajustáveis.</li>
        <li><strong>Gavetas inferiores:</strong> preferíveis a armários com portas para evitar abaixar demais.</li>
    </ul>
</section>

