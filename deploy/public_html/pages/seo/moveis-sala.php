<section id="dicas">
    <h2>Dicas de design para sala de estar</h2>
    <div class="highlight-box">
        <ul>
            <li><strong>Equilíbrio visual:</strong> alterne nichos abertos com portas fechadas para não sobrecarregar o ambiente.</li>
            <li><strong>Iluminação em camadas:</strong> combine luz geral, luz de destaque e luz indireta para criar atmosfera.</li>
            <li><strong>Cores neutras com acentos:</strong> base neutra nos móveis com pontos de cor em almofadas e objetos.</li>
            <li><strong>Proporção adequada:</strong> o painel não deve ser maior que a parede nem menor que o sofá.</li>
            <li><strong>Funcionalidade primeiro:</strong> defina o que você precisa armazenar antes de desenhar o layout.</li>
