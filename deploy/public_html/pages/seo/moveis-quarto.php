<section id="closet">
    <h2>Closet planejado</h2>
    <p>O closet é um dos itens mais desejados em um quarto planejado. Um bom projeto de closet considera:</p>
    <ul>
        <li><strong>Zonas de organização:</strong> área para roupas penduradas (curtas e longas), prateleiras para dobrados, gavetas para acessórios.</li>
        <li><strong>Sapatários:</strong> prateleiras inclinadas ou nichos específicos para calçados.</li>
        <li><strong>Iluminação interna:</strong> sensores de presença que acendem ao abrir as portas.</li>
        <li><strong>Espelhos:</strong> embutidos nas portas ou nas laterais para facilitar a visualização.</li>
        <li><strong>Gavetas organizadoras:</strong> divisórias para cintos, gravatas, joias e acessórios.</li>
    </ul>
</section>

<section id="cabeceira">
    <h2>Cabeceira sob medida</h2>
    <p>A cabeceira planejada é um elemento que faz toda a diferença no quarto. Além de proteger a parede, ela pode incluir:</p>
    <ul>
        <li>Nichos laterais para livros e óculos</li>
        <li>Iluminação indireta com fitas de LED</li>
        <li>Tomadas e USB embutidos</li>
        <li>Painel estofado para maior conforto</li>
        <li>Prateleiras integradas para objetos decorativos</li>
    </ul>
</section>

<section id="criado">
    <h2>Criados-mudos e painéis</h2>
    <p>Os criados-mudos planejados podem ser integrados à cabeceira ou projetados separadamente, com gavetas, nichos e espaço para carregar celular. Já os painéis de parede podem unir a cama, os criados-mudos e até uma escrivaninha em um único design coeso.</p>
</section>

<section id="suite">
    <h2>Suíte master completa</h2>
    <p>Para suítes master, o projeto pode incluir:</p>
    <ul>
        <li>Cama box com cabeceira planejada</li>
        <li>Closet aberto ou fechado</li>
        <li>Painel para TV</li>
        <li>Escrivaninha ou penteadeira</li>
        <li>Banheiro integrado com móveis planejados</li>
    </ul>
</section>

