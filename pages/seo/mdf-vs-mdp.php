<section id="mdf">
    <h2>O que é MDF?</h2>
    <p>MDF (Medium Density Fiberboard) é uma chapa de fibra de madeira de média densidade, fabricada a partir de fibras de madeira prensadas com resina sintética sob alta temperatura e pressão. O resultado é um material homogêneo, denso e com superfície extremamente lisa.</p>
    <p><strong>Principais características:</strong></p>
    <ul>
        <li>Superfície lisa e uniforme</li>
        <li>Alta densidade e resistência</li>
        <li>Não apresenta veios ou nós</li>
        <li>Aceita usinagem detalhada (entalhes, curvas, relevos)</li>
        <li>Pode ser pintado ou revestido com laminados</li>
    </ul>
</section>

<section id="mdp">
    <h2>O que é MDP?</h2>
    <p>MDP (Medium Density Particleboard) é uma chapa de partículas de madeira de média densidade, composta por lascas de madeira prensadas com resina. As partículas maiores ficam no centro e as mais finas nas superfícies, formando uma estrutura em camadas.</p>
    <p><strong>Principais características:</strong></p>
    <ul>
        <li>Boa resistência estrutural para prateleiras</li>
        <li>Menor preço em comparação ao MDF</li>
        <li>Menor densidade e peso</li>
        <li>Não recomendado para usinagem detalhada</li>
        <li>Acabamento superficial ligeiramente texturizado</li>
    </ul>
</section>

