<section id="perguntas">
    <h2>Perguntas Frequentes</h2>
    <div class="faq-item">
        <h3>MDF é melhor que MDP?</h3>
        <p>Não necessariamente. Cada material tem sua aplicação ideal. O MDF é superior para acabamento e usinagem, enquanto o MDP oferece melhor custo-benefício para estruturas internas.</p>
    </div>
    <div class="faq-item">
        <h3>MDF racha com facilidade?</h3>
        <p>Não, o MDF é resistente e não racha sob parafusamento quando bem executado. Para maior segurança, recomenda-se usar buchas próprias.</p>
    </div>
    <div class="faq-item">
        <h3>Qual material é mais sustentável?</h3>
        <p>Ambos utilizam resíduos de madeira, sendo mais sustentáveis que madeira maciça. Verifique a certificação FSC ou CARB dos fabricantes.</p>
    </div>
