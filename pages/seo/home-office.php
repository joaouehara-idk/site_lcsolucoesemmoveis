<section id="iluminacao">
    <h2>Iluminação adequada</h2>
    <p>A iluminação correta reduz o cansaço visual e melhora o foco. Para home offices planejados:</p>
    <ul>
        <li><strong>Luz natural:</strong> posicione a mesa de lado para a janela (não de frente nem de costas).</li>
        <li><strong>Luz geral:</strong> plafon ou trilho de LED com temperatura neutra (4000K a 5000K).</li>
        <li><strong>Luz de tarefa:</strong> luminária de mesa com braço articulado e luz direcionável.</li>
        <li><strong>Fita de LED sob prateleiras:</strong> iluminação complementar sem sombras.</li>
    </ul>
</section>

<section id="dicas">
    <h2>Dicas de produtividade</h2>
    <div class="highlight-box">
        <ul>
            <li>Mantenha a mesa desobstruída &mdash; apenas computador, caderno e um item pessoal.</li>
            <li>Use organizadores de gaveta para separar material de escritório.</li>
            <li>Tenha um quadro magnético ou mural para lembretes visuais.</li>
            <li>Invista em uma boa cadeira &mdash; é o equipamento mais importante depois do computador.</li>
            <li>Personalize o espaço com plantas, quadros ou fotos para tornar o ambiente agradável.</li>
        </ul>
