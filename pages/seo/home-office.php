<section id="importancia">
    <h2>Importância do home office planejado</h2>
    <p>Trabalhar em casa pode ser desafiador sem um ambiente adequado. Um home office planejado oferece:</p>
    <ul>
        <li><strong>Separação entre trabalho e lazer:</strong> um espaço dedicado ajuda a desligar do expediente.</li>
        <li><strong>Organização:</strong> cada item tem seu lugar, eliminando a bagunça de papéis e cabos.</li>
        <li><strong>Profissionalismo:</strong> para videoconferências, um fundo organizado passa credibilidade.</li>
        <li><strong>Conforto:</strong> móveis na altura certa previnem dores nas costas e lesões por esforço repetitivo.</li>
    </ul>
</section>

<section id="ergonomia">
    <h2>Ergonomia e saúde</h2>
    <p>A ergonomia é o aspecto mais importante de um home office. Móveis planejados permitem ajustar cada detalhe:</p>
    <div class="highlight-box">
        <ul>
            <li><strong>Mesa na altura correta:</strong> entre 72cm e 76cm para digitação confortável.</li>
            <li><strong>Monitor no nível dos olhos:</strong> suporte ou nicho elevado para a tela evitar tensão cervical.</li>
            <li><strong>Gaveta para teclado:</strong> deslizante para posicionar o teclado na altura ideal.</li>
            <li><strong>Passagem de cabos:</strong> canaletas e tomadas embutidas para organização elétrica.</li>
            <li><strong>Cadeira compatível:</strong> o móvel planejado complementa, mas a cadeira ergonômica é essencial.</li>
        </ul>
    </div>
</section>

