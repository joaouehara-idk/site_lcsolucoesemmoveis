<section id="multifuncional">
    <h2>Móveis multifuncionais</h2>
    <p>A chave para otimizar apartamentos pequenos são os móveis que servem a mais de um propósito:</p>
    <ul>
        <li><strong>Sofá-cama planejado:</strong> para o home office que vira quarto de hóspedes.</li>
        <li><strong>Mesa dobrável:</strong> fixada na parede com tampo que se recolhe quando não está em uso.</li>
        <li><strong>Estante com escrivaninha:</strong> nichos superiores para livros e inferior para trabalho.</li>
        <li><strong>Cama com gavetas:</strong> baú planejado para lençóis, cobertores e roupas de estação.</li>
        <li><strong>Painel multifuncional:</strong> TV central, nichos nas laterais e prateleiras flutuantes.</li>
    </ul>
</section>

<section id="cozinha-ap">
    <h2>Cozinha de apartamento</h2>
    <p>Em cozinhas de apartamento, cada centímetro conta. Soluções planejadas incluem:</p>
    <ul>
        <li>Armários até o teto para aproveitar toda a altura disponível</li>
        <li>Gavetas com divisórias para talheres, utensílios e panelas</li>
        <li>Porta-temperos e porta-rolos internos nas portas dos armários</li>
        <li>Lixeira embutida na bancada</li>
        <li>Carrinho ou módulo sobre rodas para ampliar a bancada quando necessário</li>
    </ul>
</section>

<section id="quarto-ap">
    <h2>Quarto de apartamento</h2>
    <p>Para quartos de apartamento, as melhores soluções planejadas são:</p>
    <ul>
        <li><strong>Cama box com baú:</strong> aproveita o espaço embaixo da cama para armazenamento sazonal.</li>
        <li><strong>Closet compacto:</strong> portas de correr para economizar espaço, com organização interna otimizada.</li>
        <li><strong>Cabeceira com nichos:</strong> substitui criados-mudos, liberando espaço nas laterais.</li>
        <li><strong>Armário aéreo:</strong> acima da cama para roupas de cama e itens pouco usados.</li>
    </ul>
</section>

<section id="sala-ap">
    <h2>Sala de apartamento</h2>
    <p>Na sala, o foco está em criar ambientes integrados sem sensação de aperto:</p>
    <ul>
        <li><strong>Painel fino para TV:</strong> com no máximo 35cm de profundidade para não avançar no ambiente.</li>
        <li><strong>Estantes suspensas:</strong> liberam o chão e dão sensação de amplitude.</li>
        <li><strong>Mesa de centro com armazenamento:</strong> ideal para controles, revistas e mantas.</li>
        <li><strong>Espelhos nas portas de armário:</strong> ampliam visualmente o espaço.</li>
    </ul>
</section>

