                    </button>
                    <div class="tech-faq-answer">
                        <p>
                            Nossos móveis seguem as especificações dos fabricantes de ferragens e componentes, com garantia conforme o fornecedor. Ferragens como dobradiças e corrediças têm garantia separada, fornecida pelo fabricante (geralmente 1 a 3 anos). A garantia não cobre danos causados por uso indevido, umidade excessiva além do especificado no projeto ou modificações feitas por terceiros. Após a instalação, entregamos
